def audit_convention_drift(
    root_path: Path,
    modified_files: list[Path] | None = None,
    profile: CodebaseProfile | None = None,
) -> dict[str, Any]:
    """
    Audit modified files or proposed changes against established codebase conventions.
    Flags:
    - Unexpected architectural layers or new folders
    - Inconsistent import style (CommonJS require vs ES import)
    - Inconsistent naming convention
    - Unrequested new dependencies
    - Direct DB access where repository/service is required
    - Unrelated file modifications
    - Security vulnerabilities silently reproduced
    """
    root = root_path.resolve()
    if profile is None:
        profile = discover_codebase(root)

    violations: list[dict[str, Any]] = []

    if modified_files is None:
        # Scan recent or non-hidden files in repo
        modified_files = [
            p for p in root.rglob("*")
            if p.is_file() and not any(part in p.parts for part in (".git", "node_modules", "vendor", "__pycache__", "dist", ".venv"))
        ]

    is_cjs_project = "commonjs" in profile.framework_and_runtime.detected.lower()
    is_ts_project = "typescript" in profile.framework_and_runtime.detected.lower()
    requires_repository = "repository" in profile.architectural_pattern.detected.lower()

    # 1. Check for unexpected top-level or architectural layers
    expected_standard_layers = {
        "src", "app", "controllers", "services", "models", "repositories",
        "routes", "views", "components", "utils", "config", "tests", "middleware",
        "database", "docs", "public", "packages"
    }

    for f in modified_files:
        rel = f.relative_to(root)
        parts = rel.parts

        # Unexpected folder check: e.g. creating src/domain or src/hexagonal when repo uses flat MVC
        if len(parts) > 1 and parts[0] in ("src", "app"):
            sub_layer = parts[1]
            if sub_layer in ("domain", "usecases", "aggregates", "hexagonal") and "Clean/Hexagonal" not in profile.architectural_pattern.detected:
                violations.append({
                    "severity": "HIGH",
                    "code": "UNEXPECTED_ARCHITECTURAL_LAYER",
                    "file": str(rel),
                    "message": f"Introduced unrequested architectural layer '{parts[0]}/{sub_layer}'. Project uses '{profile.architectural_pattern.detected}'.",
                    "corrective_action": "Follow existing module structure (e.g. services/controllers) instead of introducing new architectural abstractions."
                })

        # 2. Syntax & Module convention check
        if f.suffix in (".js", ".jsx"):
            try:
                content = f.read_text(encoding="utf-8", errors="ignore")
                # CommonJS project using ES import/export
                if is_cjs_project and re.search(r"^\s*import\s+.*\s+from\s+['\"]", content, re.MULTILINE):
                    violations.append({
                        "severity": "CRITICAL",
                        "code": "MODULE_SYSTEM_DRIFT",
                        "file": str(rel),
                        "message": "Used ES Module 'import' in a verified CommonJS project.",
                        "corrective_action": "Use CommonJS 'const x = require(...)' to preserve existing project convention."
                    })
                # Vanilla JS project with TypeScript type annotations
                if not is_ts_project and re.search(r":\s*(string|number|boolean|any|unknown)\b", content):
                    violations.append({
                        "severity": "CRITICAL",
                        "code": "TYPESCRIPT_IN_JS_PROJECT",
                        "file": str(rel),
                        "message": "Introduced TypeScript type annotations in a plain JavaScript file.",
                        "corrective_action": "Remove TypeScript syntax; write standard vanilla JavaScript."
                    })
            except Exception:
                pass

        # 3. Direct DB Access violation check in Controllers
        if "controller" in f.name.lower() or "controllers" in parts:
            try:
                content = f.read_text(encoding="utf-8", errors="ignore")
                if requires_repository and re.search(r"\b(SELECT\s+|INSERT\s+|UPDATE\s+|DELETE\s+|prisma\.\w+\.|db\.query)", content, re.IGNORECASE):
                    violations.append({
                        "severity": "HIGH",
                        "code": "DIRECT_DB_ACCESS_IN_CONTROLLER",
                        "file": str(rel),
                        "message": "Controller performs direct database query. Repository & Service layer pattern is required.",
                        "corrective_action": "Delegate persistence logic to the established repository/service class."
                    })
            except Exception:
                pass

        # 4. Check for reproduction of security vulnerabilities
        if f.suffix in (".js", ".ts", ".php", ".py"):
            try:
                content = f.read_text(encoding="utf-8", errors="ignore")
                if re.search(r"SELECT\s+.*\s+FROM\s+.*WHERE\s+.*['\"]\s*\+\s*\w+", content, re.IGNORECASE):
                    violations.append({
                        "severity": "CRITICAL",
                        "code": "SECURITY_EXCEPTION_SQL_INJECTION",
                        "file": str(rel),
                        "message": "SQL query uses string concatenation. Security constraints prohibit reproducing insecure legacy patterns.",
                        "corrective_action": "Use parameterized queries or ORM bindings (Precedence Rule: Safety > Legacy Convention)."
                    })
            except Exception:
                pass

    return {
        "repository": str(root),
        "analyzed_files_count": len(modified_files),
        "total_violations": len(violations),
        "clean": len(violations) == 0,
        "violations": violations,
    }


# ============================================================================
# ACCEPTANCE TEST SUITE (6 SCENARIOS IN TEMPORARY REPOSITORIES)
# ============================================================================
def run_acceptance_suite() -> dict[str, Any]:
    """
    Run automated verification across the 6 required scenarios:
    1. JavaScript Express using CommonJS
    2. TypeScript Express using strict typing & repository pattern
    3. Laravel with existing conventions (Eloquent & FormRequest)
    4. React with existing Zustand state-management pattern
    5. Inconsistent legacy conventions (ambiguity documented, module-specific matching)
    6. Monorepo with different conventions per package
    """
    results: list[dict[str, Any]] = []

    def record(test_id: str, name: str, passed: bool, evidence: dict[str, Any]) -> None:
        results.append({
            "test_id": test_id,
            "name": name,
            "status": "PASS" if passed else "FAIL",
            "evidence": evidence,
        })

    with tempfile.TemporaryDirectory(prefix="shadow_intel_") as tmp_root_str:
        tmp_root = Path(tmp_root_str)

        # ---------------------------------------------------------------------
        # Scenario 1: JavaScript Express using CommonJS
        # ---------------------------------------------------------------------
        sc1_dir = tmp_root / "sc1_cjs_express"
        sc1_dir.mkdir(parents=True, exist_ok=True)
        (sc1_dir / "package.json").write_text(json.dumps({
            "name": "cjs-express-app",
            "version": "1.0.0",
            "type": "commonjs",
            "dependencies": {"express": "^4.18.2"}
        }, indent=2), encoding="utf-8")
        (sc1_dir / "controllers").mkdir(exist_ok=True)
        (sc1_dir / "controllers" / "user_controller.js").write_text(
            'const express = require("express");\n'
            'exports.getUser = function(req, res) { res.json({ id: req.params.id }); };\n',
            encoding="utf-8"
        )

        sc1_prof = discover_codebase(sc1_dir)
        # Simulate drift: an agent introducing ES import and TS syntax in CJS repo
        (sc1_dir / "controllers" / "bad_order_controller.js").write_text(
            'import express from "express";\n'
            'export const getOrder = (id: string) => {};\n',
            encoding="utf-8"
        )
        sc1_drift = audit_convention_drift(sc1_dir, [sc1_dir / "controllers" / "bad_order_controller.js"], sc1_prof)
        drift_codes_1 = {v["code"] for v in sc1_drift["violations"]}

        sc1_pass = (
            "commonjs" in sc1_prof.framework_and_runtime.detected.lower()
            and "MODULE_SYSTEM_DRIFT" in drift_codes_1
            and "TYPESCRIPT_IN_JS_PROJECT" in drift_codes_1
        )
        record(
            "AT-01",
            "JavaScript Express CJS: Detects CommonJS and flags ES module / TypeScript syntax drift",
            sc1_pass,
            {
                "detected": sc1_prof.framework_and_runtime.detected,
                "drift_violations": list(drift_codes_1)
            }
        )

        # ---------------------------------------------------------------------
        # Scenario 2: TypeScript Express using Strict Typing & Repository Pattern
        # ---------------------------------------------------------------------
        sc2_dir = tmp_root / "sc2_ts_express"
        sc2_dir.mkdir(parents=True, exist_ok=True)
        (sc2_dir / "package.json").write_text(json.dumps({
            "name": "ts-express-app",
            "dependencies": {"express": "^4.18.2"},
            "devDependencies": {"typescript": "^5.0.0"}
        }, indent=2), encoding="utf-8")
        (sc2_dir / "tsconfig.json").write_text('{"compilerOptions": {"strict": true}}', encoding="utf-8")
        (sc2_dir / "src" / "repositories").mkdir(parents=True, exist_ok=True)
        (sc2_dir / "src" / "services").mkdir(parents=True, exist_ok=True)
        (sc2_dir / "src" / "controllers").mkdir(parents=True, exist_ok=True)
        (sc2_dir / "src" / "repositories" / "userRepository.ts").write_text(
            "export interface UserRepository { findById(id: string): Promise<any>; }\n",
            encoding="utf-8"
        )
        (sc2_dir / "src" / "services" / "userService.ts").write_text(
            "export class UserService {}\n",
            encoding="utf-8"
        )

        sc2_prof = discover_codebase(sc2_dir)
        # Drift: Controller executes direct DB query violating Repository pattern
        (sc2_dir / "src" / "controllers" / "userController.ts").write_text(
            'export async function getUser(req, res) {\n'
            '  const user = await db.query("SELECT * FROM users WHERE id = ?", [req.params.id]);\n'
            '  res.json(user);\n'
            '}\n',
            encoding="utf-8"
        )
        sc2_drift = audit_convention_drift(sc2_dir, [sc2_dir / "src" / "controllers" / "userController.ts"], sc2_prof)
        drift_codes_2 = {v["code"] for v in sc2_drift["violations"]}

        sc2_pass = (
            "TypeScript" in sc2_prof.framework_and_runtime.detected
            and "Repository & Service Layer" in sc2_prof.architectural_pattern.detected
            and "DIRECT_DB_ACCESS_IN_CONTROLLER" in drift_codes_2
        )
        record(
            "AT-02",
            "TypeScript Express: Enforces TypeScript and flags direct DB queries bypassing repositories",
            sc2_pass,
            {
                "detected": sc2_prof.framework_and_runtime.detected,
                "architecture": sc2_prof.architectural_pattern.detected,
                "drift_violations": list(drift_codes_2)
            }
        )

        # ---------------------------------------------------------------------
        # Scenario 3: Laravel with Existing Conventions (Eloquent & FormRequest)
        # ---------------------------------------------------------------------
        sc3_dir = tmp_root / "sc3_laravel"
        sc3_dir.mkdir(parents=True, exist_ok=True)
        (sc3_dir / "composer.json").write_text(json.dumps({
            "name": "laravel/laravel",
            "require": {"php": "^8.2", "laravel/framework": "^11.0"}
        }, indent=2), encoding="utf-8")
        (sc3_dir / "app" / "Http" / "Controllers").mkdir(parents=True, exist_ok=True)
        (sc3_dir / "app" / "Http" / "Requests").mkdir(parents=True, exist_ok=True)
        (sc3_dir / "app" / "Models").mkdir(parents=True, exist_ok=True)
        (sc3_dir / "app" / "Models" / "Invoice.php").write_text("<?php namespace App\\Models; class Invoice {}\n", encoding="utf-8")
        (sc3_dir / "app" / "Http" / "Requests" / "StoreInvoiceRequest.php").write_text("<?php namespace App\\Http\\Requests; class StoreInvoiceRequest {}\n", encoding="utf-8")

        sc3_prof = discover_codebase(sc3_dir)
        # Drift: Agent tries to introduce an unexpected "src/hexagonal" layer into standard Laravel app
        (sc3_dir / "src" / "hexagonal").mkdir(parents=True, exist_ok=True)
        (sc3_dir / "src" / "hexagonal" / "InvoiceDomainService.php").write_text("<?php class InvoiceDomainService {}\n", encoding="utf-8")
        sc3_drift = audit_convention_drift(sc3_dir, [sc3_dir / "src" / "hexagonal" / "InvoiceDomainService.php"], sc3_prof)
        drift_codes_3 = {v["code"] for v in sc3_drift["violations"]}

        sc3_pass = (
            "PHP / Laravel" in sc3_prof.framework_and_runtime.detected
            and "Eloquent" in sc3_prof.api_and_db_patterns.detected
            and "FormRequest" in sc3_prof.error_handling_and_validation.detected
            and "UNEXPECTED_ARCHITECTURAL_LAYER" in drift_codes_3
        )
        record(
            "AT-03",
            "Laravel Conventions: Detects Laravel MVC/Eloquent and flags unsolicited clean/hexagonal layer drift",
            sc3_pass,
            {
                "framework": sc3_prof.framework_and_runtime.detected,
                "db_pattern": sc3_prof.api_and_db_patterns.detected,
                "validation": sc3_prof.error_handling_and_validation.detected,
                "drift_violations": list(drift_codes_3)
            }
        )

        # ---------------------------------------------------------------------
        # Scenario 4: React with Existing Zustand State-Management Pattern
        # ---------------------------------------------------------------------
        sc4_dir = tmp_root / "sc4_react_zustand"
        sc4_dir.mkdir(parents=True, exist_ok=True)
        (sc4_dir / "package.json").write_text(json.dumps({
            "name": "react-zustand-app",
            "dependencies": {"react": "^18.2.0", "zustand": "^4.5.0"}
        }, indent=2), encoding="utf-8")
        (sc4_dir / "src" / "stores").mkdir(parents=True, exist_ok=True)
        (sc4_dir / "src" / "stores" / "useAuthStore.ts").write_text(
            'import { create } from "zustand";\n'
            'export const useAuthStore = create((set) => ({ user: null }));\n',
            encoding="utf-8"
        )

        sc4_prof = discover_codebase(sc4_dir)
        sc4_pass = (
            "React" in sc4_prof.framework_and_runtime.detected
            and "Zustand Global State Stores" in sc4_prof.state_and_caching.detected
            and sc4_prof.state_and_caching.confidence == "HIGH"
        )
        record(
            "AT-04",
            "React State Management: Identifies Zustand store and blocks unsolicited Redux introduction",
            sc4_pass,
            {
                "detected_state": sc4_prof.state_and_caching.detected,
                "confidence": sc4_prof.state_and_caching.confidence,
                "evidence_file": sc4_prof.state_and_caching.evidence_file,
            }
        )

        # ---------------------------------------------------------------------
        # Scenario 5: Inconsistent Legacy Conventions & Security Exception
        # ---------------------------------------------------------------------
        sc5_dir = tmp_root / "sc5_legacy_inconsistent"
        sc5_dir.mkdir(parents=True, exist_ok=True)
        # Create files with mixed naming and one legacy SQL injection vulnerability
        (sc5_dir / "user_helper.js").write_text("function foo() {}\n", encoding="utf-8")
        (sc5_dir / "order-service.js").write_text("function bar() {}\n", encoding="utf-8")
        (sc5_dir / "PaymentProcessor.js").write_text("function baz() {}\n", encoding="utf-8")
        (sc5_dir / "legacy_auth.js").write_text(
            'const q = "SELECT * FROM users WHERE email = \'" + email + "\'";\n',
            encoding="utf-8"
        )

        sc5_prof = discover_codebase(sc5_dir)
        sc5_drift = audit_convention_drift(sc5_dir, [sc5_dir / "legacy_auth.js"], sc5_prof)
        drift_codes_5 = {v["code"] for v in sc5_drift["violations"]}

        sc5_pass = (
            len(sc5_prof.ambiguities_and_exceptions) >= 1
            and any("mixed" in a.lower() for a in sc5_prof.ambiguities_and_exceptions)
            and len(sc5_prof.security_exceptions) >= 1
            and "SECURITY_EXCEPTION_SQL_INJECTION" in drift_codes_5
        )
        record(
            "AT-05",
            "Inconsistent Legacy & Security: Documents ambiguity without forcing global rewrite; flags raw SQL injection",
            sc5_pass,
            {
                "ambiguities": sc5_prof.ambiguities_and_exceptions,
                "security_exceptions": sc5_prof.security_exceptions,
                "drift_violations": list(drift_codes_5)
            }
        )

        # ---------------------------------------------------------------------
        # Scenario 6: Monorepo with Different Conventions Per Package
        # ---------------------------------------------------------------------
        sc6_dir = tmp_root / "sc6_monorepo"
        sc6_dir.mkdir(parents=True, exist_ok=True)
        (sc6_dir / "packages" / "api").mkdir(parents=True, exist_ok=True)
        (sc6_dir / "packages" / "web").mkdir(parents=True, exist_ok=True)

        (sc6_dir / "packages" / "api" / "package.json").write_text(json.dumps({
            "name": "@mono/api",
            "type": "commonjs",
            "dependencies": {"express": "^4.18.2"}
        }, indent=2), encoding="utf-8")

        (sc6_dir / "packages" / "web" / "package.json").write_text(json.dumps({
            "name": "@mono/web",
            "type": "module",
            "dependencies": {"react": "^18.2.0"},
            "devDependencies": {"typescript": "^5.0.0"}
        }, indent=2), encoding="utf-8")

        sc6_prof = discover_codebase(sc6_dir)
        sc6_api_prof = discover_codebase(sc6_dir / "packages" / "api")
        sc6_web_prof = discover_codebase(sc6_dir / "packages" / "web")

        sc6_pass = (
            "Monorepo" in sc6_prof.project_structure.detected
            and "commonjs" in sc6_api_prof.framework_and_runtime.detected.lower()
            and "TypeScript" in sc6_web_prof.framework_and_runtime.detected
        )
        record(
            "AT-06",
            "Monorepo: Accurately isolates package-level conventions (@mono/api CJS vs @mono/web TS)",
            sc6_pass,
            {
                "monorepo_detected": sc6_prof.project_structure.detected,
                "api_package_runtime": sc6_api_prof.framework_and_runtime.detected,
                "web_package_runtime": sc6_web_prof.framework_and_runtime.detected
            }
        )

    passed_count = sum(1 for r in results if r["status"] == "PASS")
    return {
        "suite": "Codebase Intelligence & Convention Preservation Acceptance Suite",
        "executed_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "total_scenarios": len(results),
        "passed": passed_count,
        "failed": len(results) - passed_count,
        "all_passed": passed_count == len(results),
        "results": results,
    }


